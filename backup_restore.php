// Function to generate SQL Dump string
function generateDatabaseDump($db) {
    $out = "-- ========================================================\n";
    $out .= "-- Database Backup: " . DB_NAME . "\n";
    $out .= "-- Generated by AGSmart POS System\n";
    $out .= "-- Date: " . date('Y-m-d H:i:s') . "\n";
    $out .= "-- ========================================================\n\n";
    $out .= "SET SQL_MODE = \"NO_AUTO_VALUE_ON_ZERO\";\n";
    $out .= "START TRANSACTION;\n";
    $out .= "SET time_zone = \"+00:00\";\n\n";
    $out .= "/*!40101 SET @OLD_CHARACTER_SET_CLIENT=@@CHARACTER_SET_CLIENT */;\n";
    $out .= "/*!40101 SET @OLD_CHARACTER_SET_RESULTS=@@CHARACTER_SET_RESULTS */;\n";
    $out .= "/*!40101 SET @OLD_COLLATION_CONNECTION=@@COLLATION_CONNECTION */;\n";
    $out .= "/*!40101 SET NAMES utf8mb4 */;\n\n";

    // Disable foreign key checks during import
    $out .= "SET FOREIGN_KEY_CHECKS = 0;\n\n";

    // 1. Get Tables (exclude views for table dump)
    $stmtTables = $db->query("SHOW FULL TABLES WHERE Table_type = 'BASE TABLE'");
    $tables = [];
    while ($row = $stmtTables->fetch(PDO::FETCH_NUM)) {
        $tables[] = $row[0];
    }

    foreach ($tables as $tbl) {
        $out .= "-- --------------------------------------------------------\n";
        $out .= "-- Structure for table `$tbl`\n";
        $out .= "-- --------------------------------------------------------\n";
        $out .= "DROP TABLE IF EXISTS `$tbl`;\n";
        
        $createStmt = $db->query("SHOW CREATE TABLE `$tbl`")->fetch(PDO::FETCH_NUM);
        $out .= $createStmt[1] . ";\n\n";

        // Table Data
        $dataStmt = $db->query("SELECT * FROM `$tbl`");
        $rows = $dataStmt->fetchAll(PDO::FETCH_ASSOC);

        if (!empty($rows)) {
            $out .= "-- Dumping data for table `$tbl`\n";
            $columns = array_keys($rows[0]);
            $colList = implode('`, `', $columns);

            $chunks = array_chunk($rows, 100);
            foreach ($chunks as $chunk) {
                $out .= "INSERT INTO `$tbl` (`$colList`) VALUES\n";
                $rowStrings = [];
                foreach ($chunk as $r) {
                    $valStrings = [];
                    foreach ($r as $val) {
                        if ($val === null) {
                            $valStrings[] = "NULL";
                        } else {
                            $valStrings[] = $db->quote($val);
                        }
                    }
                    $rowStrings[] = "(" . implode(', ', $valStrings) . ")";
                }
                $out .= implode(",\n", $rowStrings) . ";\n";
            }
            $out .= "\n";
        }
    }

    // 2. Get Views
    $stmtViews = $db->query("SHOW FULL TABLES WHERE Table_type = 'VIEW'");
    while ($vRow = $stmtViews->fetch(PDO::FETCH_NUM)) {
        $viewName = $vRow[0];
        $out .= "-- --------------------------------------------------------\n";
        $out .= "-- Structure for view `$viewName`\n";
        $out .= "-- --------------------------------------------------------\n";
        $out .= "DROP VIEW IF EXISTS `$viewName`;\n";
        
        $createView = $db->query("SHOW CREATE VIEW `$viewName`")->fetch(PDO::FETCH_NUM);
        if ($createView && isset($createView[1])) {
            $out .= $createView[1] . ";\n\n";
        }
    }

    $out .= "SET FOREIGN_KEY_CHECKS = 1;\n";
    $out .= "COMMIT;\n\n";
    $out .= "/*!40101 SET CHARACTER_SET_CLIENT=@OLD_CHARACTER_SET_CLIENT */;\n";
    $out .= "/*!40101 SET CHARACTER_SET_RESULTS=@OLD_CHARACTER_SET_RESULTS */;\n";
    $out .= "/*!40101 SET COLLATION_CONNECTION=@OLD_COLLATION_CONNECTION */;\n";

    return $out;
}

// Function to execute SQL file/script
function executeSqlScript($pdo, $sql) {
    // Strip comments and split by semicolon safely
    $pdo->exec("SET FOREIGN_KEY_CHECKS = 0;");
    
    // Execute multiple statements
    $pdo->exec($sql);
    
    $pdo->exec("SET FOREIGN_KEY_CHECKS = 1;");
}

// Handle Form Submissions
if ($_SERVER['REQUEST_METHOD'] === 'POST' && isset($_POST['action'])) {
    $action = $_POST['action'];

    // Action 1: Download Backup SQL
    if ($action === 'backup_download') {
        if (!$db) {
            setFlash('danger', 'Koneksi database tidak tersedia.');
            header("Location: backup_restore.php");
            exit;
        }

        try {
            $dump = generateDatabaseDump($db);
            $filename = DB_NAME . '_backup_' . date('Y-m-d_His') . '.sql';

            header('Content-Description: File Transfer');
            header('Content-Type: application/octet-stream');
            header('Content-Disposition: attachment; filename="' . $filename . '"');
            header('Expires: 0');
            header('Cache-Control: must-revalidate');
            header('Pragma: public');
            header('Content-Length: ' . strlen($dump));
            echo $dump;
            exit;
        } catch (Exception $e) {
            setFlash('danger', 'Gagal membuat backup: ' . $e->getMessage());
            header("Location: backup_restore.php");
            exit;
        }
    }

    // Action 2: Save Backup to Server
    if ($action === 'backup_server') {
        if (!$db) {
            setFlash('danger', 'Koneksi database tidak tersedia.');
        } else {
            try {
                $dump = generateDatabaseDump($db);
                $filename = DB_NAME . '_backup_' . date('Y-m-d_His') . '.sql';
                file_put_contents($backupDir . '/' . $filename, $dump);
                setFlash('success', "Backup berhasil disimpan di server: <b>$filename</b>");
            } catch (Exception $e) {
                setFlash('danger', 'Gagal membuat backup di server: ' . $e->getMessage());
            }
        }
        header("Location: backup_restore.php");
        exit;
    }

    // Action 3: Restore from Uploaded File
    if ($action === 'restore_upload') {
        if (!isset($_FILES['sql_file']) || $_FILES['sql_file']['error'] !== UPLOAD_ERR_OK) {
            setFlash('danger', 'Silakan pilih file .sql yang valid untuk di-restore!');
        } else {
            $fileTmp = $_FILES['sql_file']['tmp_name'];
            $fileName = $_FILES['sql_file']['name'];
            $ext = strtolower(pathinfo($fileName, PATHINFO_EXTENSION));

            if ($ext !== 'sql') {
                setFlash('danger', 'Format file harus berupa .sql!');
            } else {
                try {
                    $sqlContent = file_get_contents($fileTmp);
                    executeSqlScript($db, $sqlContent);
                    setFlash('success', "Database berhasil di-restore dari file: <b>$fileName</b>!");
                } catch (Exception $e) {
                    setFlash('danger', 'Gagal me-restore database: ' . $e->getMessage());
                }
            }
        }
        header("Location: backup_restore.php");
        exit;
    }

    // Action 4: Restore from Existing Local Backup File
    if ($action === 'restore_local') {
        $file = basename($_POST['filename']);
        $filePath = $backupDir . '/' . $file;

        if (file_exists($filePath)) {
            try {
                $sqlContent = file_get_contents($filePath);
                executeSqlScript($db, $sqlContent);
                setFlash('success', "Database berhasil di-restore dari backup <b>$file</b>!");
            } catch (Exception $e) {
                setFlash('danger', 'Gagal me-restore database: ' . $e->getMessage());
            }
        } else {
            setFlash('danger', 'File backup tidak ditemukan!');
        }
        header("Location: backup_restore.php");
        exit;
    }

    // Action 5: Delete Local Backup File
    if ($action === 'delete_backup') {
        $file = basename($_POST['filename']);
        $filePath = $backupDir . '/' . $file;
        if (file_exists($filePath)) {
            unlink($filePath);
            setFlash('success', "File backup <b>$file</b> berhasil dihapus!");
        }
        header("Location: backup_restore.php");
        exit;
    }

    // Action 6: Reset to Default Initial State
    if ($action === 'reset_default') {
        try {
            $defaultSql = __DIR__ . '/database/db_tokokita.sql';
            if (file_exists($defaultSql)) {
                $sqlContent = file_get_contents($defaultSql);
                executeSqlScript($db, $sqlContent);
                setFlash('success', 'Database berhasil di-reset ke data bawaan lengkap!');
            }
        } catch (Exception $e) {
            setFlash('danger', 'Gagal reset database: ' . $e->getMessage());
        }
        header("Location: backup_restore.php");
        exit;
    }
}

// Scan backups directory
$localBackups = [];
if (is_dir($backupDir)) {
    $files = scandir($backupDir);
    foreach ($files as $f) {
        if ($f !== '.' && $f !== '..' && pathinfo($f, PATHINFO_EXTENSION) === 'sql') {
            $path = $backupDir . '/' . $f;
            $localBackups[] = [
                'name' => $f,
                'size' => filesize($path),
                'date' => filemtime($path)
            ];
        }
    }
    // Sort newest first
    usort($localBackups, function($a, $b) {
        return $b['date'] - $a['date'];
    });
}

